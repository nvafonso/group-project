  left_join(
    dose_results |>
      group_by(Scenario, Team) |>
      summarise(
        across(all_of(all_outcomes), ~ mean(.x)),
        requested_target_sd = first(requested_target_sd),
        .groups = "drop"
      ),
    by = c("Scenario", "Team")
  )

