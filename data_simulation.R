# ============================================================
# data_simulation.R
# Individual-level HEXACO -> teamwork-quality simulation
# ============================================================
# IMPORTANT:
# All effects and generated scores are hypothetical assumptions.
# They are not empirical findings, causal estimates, or predictions.
#
# Model:
#   Individual outcome = outcome-specific intercept
#     + individual-level HEXACO contribution
#     + team-level diversity contribution
#     + shared team random intercept
#     + outcome-specific individual residual
#
# The same team random intercept is shared across outcomes for a given
# team. Individual residuals are independently generated by outcome.
#
# Each teamwork outcome is bounded to [1, 5]. Bounding can alter
# means, variances, and apparent effect sizes.
#
# Requires R >= 4.1 and packages: dplyr, tidyr, ggplot2
# ============================================================

